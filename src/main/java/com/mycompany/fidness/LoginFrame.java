    private void btnIniciarSesionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnIniciarSesionActionPerformed
        // 1. Instanciamos un usuario de prueba (usando tu clase Cliente)
    Cliente usuarioPrueba = new Cliente("Felix", "admin123");
    
    // 2. Capturamos lo que el usuario digitó en los campos
    String usuarioDigitado = txtUsuario.getText();
    String contrasenaDigitada = new String(txtContrasena.getPassword());
    
    // 3. Aplicamos validación con try-catch y nuestra Excepción Personalizada
            try {
            // Validamos campos vacíos
            if (usuarioDigitado.trim().isEmpty() || contrasenaDigitada.trim().isEmpty()) {
                throw new FidnessException("Por favor, ingrese su usuario y contraseña.");
            }

            // Validamos credenciales
            if (usuarioPrueba.iniciarSesion(usuarioDigitado, contrasenaDigitada)) {
                // 1. Opcional: mostrar mensaje de bienvenida
                javax.swing.JOptionPane.showMessageDialog(this, "Acceso concedido. Bienvenido " + usuarioPrueba.getNombreUsuario());

                // 2. ABRIR EL DASHBOARD
                DashboardFrame dashboard = new DashboardFrame();
                dashboard.setVisible(true);

                // 3. CERRAR LA VENTANA DE LOGIN
                this.dispose(); 

            } else {
                throw new FidnessException("Credenciales incorrectas. Intente nuevamente.");
            }

        } catch (FidnessException ex) {
            javax.swing.JOptionPane.showMessageDialog(this, 
                ex.getMessage(), 
                "Error de Autenticación", 
                javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnIniciarSesionActionPerformed

