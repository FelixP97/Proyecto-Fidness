        private void inicializarDatos() {
        listaEjerciciosGlobal = new java.util.ArrayList<>();
        listaEjerciciosGlobal.add(new Ejercicio(1, "Barbell Bench Press", "Chest", "Empuje con barra"));
        listaEjerciciosGlobal.add(new Ejercicio(2, "Barbell Back Squat", "Legs", "Sentadilla libre"));
        listaEjerciciosGlobal.add(new Ejercicio(3, "Conventional Deadlift", "Back / Posterior", "Peso muerto"));
        listaEjerciciosGlobal.add(new Ejercicio(4, "Overhead Press (OHP)", "Shoulders", "Press militar"));
        listaEjerciciosGlobal.add(new Ejercicio(5, "Dumbbell Bicep Curl", "Arms", "Curl de bíceps"));
    }

    private void cargarTabla(String filtroSeleccionado) {
        javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblEjercicios.getModel();
        modelo.setRowCount(0); // Limpia las filas actuales de la tabla

        // Recorremos la colección y validamos el filtro
        for (Ejercicio ej : listaEjerciciosGlobal) {
            // Si el filtro es "todas" o coincide con la categoría del ejercicio, se agrega a la tabla
            if (filtroSeleccionado.equals("[ All Categories ]") || ej.getCategoria().equals(filtroSeleccionado)) {
                // Agregamos el Nombre, Grupo Muscular y un texto simulando el botón Action
                modelo.addRow(new Object[]{ ej.getNombre(), ej.getCategoria(), "[ ADD ]" });
            }
        }
    }

